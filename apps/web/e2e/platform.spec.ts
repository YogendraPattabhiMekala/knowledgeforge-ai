import {test,expect} from '@playwright/test';
test('demo → documents → grounded conversation → source',async({page})=>{
 await page.goto('/');await expect(page.getByRole('heading',{name:/Less searching/})).toBeVisible();
 await page.getByRole('button',{name:/Explore demo workspace/}).click();
 await expect(page.getByRole('heading',{name:/Welcome back, Alex/})).toBeVisible();
 await page.screenshot({path:`${process.env.SCREENSHOT_DIR||'../../artifacts/screenshots'}/dashboard.png`,fullPage:true});
 await page.getByRole('link',{name:'Document library'}).click();
 await expect(page.getByRole('heading',{name:'Document library'})).toBeVisible();
 await page.getByRole('button',{name:/Company handbook.md/}).first().click();
 await expect(page.getByRole('dialog',{name:'Document intelligence'})).toBeVisible();
 await expect(page.getByText('Remote work policy',{exact:false}).first()).toBeVisible();
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.getByRole('link',{name:'AI assistant'}).click();
 await page.getByRole('textbox',{name:'Ask your knowledge'}).fill('What is our remote work policy?');
 await page.getByRole('button',{name:'Send question'}).click();
 await expect(page.getByText(/Extractive mode · No AI provider/)).toBeVisible();
 await page.getByRole('button',{name:/Company handbook.md/}).first().click();
 await expect(page.getByRole('dialog',{name:'Straight from the source'})).toBeVisible();
 await expect(page.locator('blockquote')).toContainText('three days');
});
test('mobile navigation and theme',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');
 await page.getByRole('button',{name:/Explore demo workspace/}).click();
 await expect(page.getByRole('heading',{name:/Welcome back/})).toBeVisible();
 await page.screenshot({path:`${process.env.SCREENSHOT_DIR||'../../artifacts/screenshots'}/mobile.png`,fullPage:true});
 await page.getByRole('button',{name:'Open navigation'}).click();
 await page.getByRole('link',{name:'Workspaces',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Your workspaces'})).toBeVisible();
 await page.getByRole('button',{name:'Use dark theme'}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
});
test('new organization → workspace → upload → search → update access',async({page})=>{
 const email=`browser-${Date.now()}@example.test`;
 await page.goto('/register');
 await page.getByLabel('Full name').fill('Jamie Tester');
 await page.getByLabel('Organization',{exact:true}).fill('Browser Test Organization');
 await page.getByLabel('Work email').fill(email);
 await page.getByLabel('Password',{exact:true}).fill('BrowserPassword!2026');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await expect(page.getByRole('heading',{name:/Welcome back, Jamie/})).toBeVisible();
 await page.getByRole('link',{name:'Workspaces',exact:true}).click();
 await page.getByRole('button',{name:'New workspace',exact:true}).click();
 await page.getByLabel('Workspace name').fill('Browser Research');
 await page.getByLabel('Description',{exact:true}).fill('Created through the actual user interface.');
 await page.getByRole('button',{name:'Create workspace',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Browser Research'})).toBeVisible();
 await page.getByRole('link',{name:'Document library'}).click();
 await page.getByRole('button',{name:'Upload documents',exact:true}).first().click();
 await page.locator('input[type=file]').setInputFiles({name:'browser-policy.md',mimeType:'text/markdown',buffer:Buffer.from('Research access requires approval by the research lead. Keep experiments reproducible.')});
 await expect(page.getByRole('button',{name:/browser-policy.md/}).first()).toBeVisible();
 await page.getByRole('button',{name:/browser-policy.md/}).first().click();
 await expect(page.getByText('Research access requires approval',{exact:false})).toBeVisible();
 await page.getByLabel('Document access').selectOption('private');
 await page.getByRole('button',{name:'Save access',exact:true}).click();
 await expect(page.getByRole('status').last()).toContainText('permissions updated');
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.getByRole('link',{name:'Search',exact:true}).click();
 await page.getByRole('textbox',{name:'Search documents'}).fill('research approval');
 await page.getByRole('button',{name:'Search',exact:true}).click();
 await expect(page.getByRole('button',{name:/browser-policy.md/})).toBeVisible();
});
